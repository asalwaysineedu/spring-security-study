package com.spring_security.basic.cia;

public class CIA {
//    🕵️‍♀️ 1️⃣ Confidentiality (기밀성)
//    인가되지 않은 사용자가 정보에 접근하지 못하도록 보호하는 것.
//
//    예시:
//    로그인한 사용자만 마이페이지를 볼 수 있게 하는 것.
//    비밀번호, 주민등록번호 등 민감한 데이터를 암호화 저장.
//    HTTPS를 사용해 네트워크 통신 중 데이터가 노출되지 않게 함.
//
//    스프링 시큐리티에서의 예:
//    @PreAuthorize("hasRole('ADMIN')") → 특정 권한만 접근 허용
//    필터 체인에서 인증(Authentication), 인가(Authorization) 처리

//    ----------------------------------------------------------

//    ⚙️ 2️⃣ Integrity (무결성)
//    데이터가 허가되지 않은 방식으로 수정·삭제되지 않도록 보호하는 것.
//
//    예시:
//    사용자가 송금 요청을 보냈는데, 공격자가 그 금액을 중간에 바꾸지 못하게 하는 것.
//    파일이 전송 중 손상되지 않도록 디지털 서명이나 해시 검증 사용.
//
//    스프링 시큐리티에서의 예:
//    CSRF 토큰을 사용해 요청이 진짜 사용자로부터 온 것인지 검증.
//    JWT 서명(Signature)으로 토큰 변조 방지.

//    ----------------------------------------------------------

//    🌐 3️⃣ Availability (가용성)
//    시스템과 정보가 필요한 사람에게 언제든 접근 가능해야 한다는 것.
//
//    예시:
//    서버가 과부하나 공격(DDoS 등)으로 인해 다운되지 않도록 하는 것.
//    백업 및 장애 복구 시스템 구축.
//
//    스프링 시큐리티에서 직접 다루진 않지만,
//    예를 들어 계정 잠금(locking) 정책을 너무 강하게 해서 정상 사용자가 접근을 못 하면 가용성 저하가 됨 → 균형이 중요.

//    항목	    |의미	        |주요 기술/개념	        |스프링 시큐리티 적용 예시
//    C (기밀성)	|정보 접근 통제	|암호화, 접근 제어	        |Authentication / Authorization
//    I (무결성)	|데이터 변조 방지	|해시, 서명, CSRF 토큰    |	CSRF 보호, JWT 서명
//    A (가용성)	|접근 가능 보장	|백업, 장애 복구, 부하 분산 |비밀번호 정책, 서버 안정성 관리
}
